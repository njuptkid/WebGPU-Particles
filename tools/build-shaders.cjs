'use strict';
const fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..'),dir=path.join(root,'src/shaders');
const read=name=>fs.readFileSync(path.join(dir,name+'.glsl'),'utf8').replace(/\r\n/g,'\n');
const keys=['common','transport','baseVertex','baseFragment','desktopVertex','appVertex','pointFragment'];
const sources=Object.fromEntries(keys.map(k=>[k,read(k)]));
const insert=(source,marker,code)=>{
 if(!source.includes(marker))throw Error('Missing shader marker: '+marker);
 return source.replace(marker,code+'\n'+marker);
};
const helpers=read('noiseCodec')+'\n'+read('noiseCache');
sources.baseFragmentCached=insert(sources.baseFragment,'varying vec2 uv;',helpers)
 .replace('float b=birth(uv*resolution);','float b=cachedBirth(uv*resolution,unpackNoise16(texture2D(fixedNoise,gl_FragCoord.xy/noiseSize).rg)*.38);');
for(const scene of ['desktop','app']) {
 let s=insert(sources[scene+'Vertex'],'attribute vec3 p;',helpers);
 s='#define PARTICLE_NOISE\n'+s;
 s=s.replace('float b=birth(origin);','vec2 cached=particleFixedNoise();float b=cachedBirth(origin,cached.x);')
    .replace('float age=max(0.,time-birth(origin));','vec2 cached=particleFixedNoise();float age=max(0.,time-cachedBirth(origin,cached.x));')
    .replace('(noise(origin*.016)-.5)','(cached.y-.5)');
 sources[scene+'VertexCached']=s;
}
sources.noiseBakeFragment=sources.common+'\n'+read('noiseCodec')+'\n'+read('noiseBakeFragment');
sources.particleNoiseBakeVertex=sources.common+'\n'+read('noiseCodec')+'\n'+read('particleNoiseBakeVertex');
sources.particleNoiseBakeFragment=read('particleNoiseBakeFragment');
sources.experiments=require('./shader-experiments.cjs')(sources,read);
// Historical release pattern, only for the before/after visual comparison.
sources.legacy=Object.fromEntries(['baseFragment','appVertex','desktopVertex'].map(k=>[
 k,sources[k].replace('grainHash(floor(p*.65))','hash(floor(p*.65))')
]));
fs.writeFileSync(path.join(root,'src/shader-sources.js'),
 '// Generated by node tools/build-shaders.cjs. Edit src/shaders/*.glsl.\nwindow.ParticleShaders='+JSON.stringify(sources,null,2)+';\n');
console.log('Built '+Object.keys(sources).length+' shader sources');
